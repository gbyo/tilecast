#!/usr/bin/env node
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const sourcePath = resolve(
  root,
  "packages/manifest-schema/presentation-capabilities.json",
);
const contract = JSON.parse(readFileSync(sourcePath, "utf8"));

if (contract.schemaVersion !== 1 || !Array.isArray(contract.capabilities)) {
  throw new Error("presentation capability contract must use schemaVersion 1");
}

const seen = new Set();
const capabilities = contract.capabilities
  .map((entry) => {
    if (!entry || typeof entry !== "object") {
      throw new Error("capability entry must be an object");
    }
    const { name, version, baseline } = entry;
    if (typeof name !== "string" || !/^[a-z][a-z0-9_.-]*$/.test(name)) {
      throw new Error(`invalid capability name: ${String(name)}`);
    }
    if (seen.has(name)) throw new Error(`duplicate capability: ${name}`);
    seen.add(name);
    if (!Number.isInteger(version) || version < 1) {
      throw new Error(`invalid version for ${name}`);
    }
    if (typeof baseline !== "boolean") {
      throw new Error(`baseline must be boolean for ${name}`);
    }
    return { name, version, baseline };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

const all = capabilities.map(({ name, version }) => [name, version]);
const baseline = capabilities
  .filter((entry) => entry.baseline)
  .map(({ name, version }) => [name, version]);
const tsMap = (entries) =>
  entries
    .map(([name, version]) => `  ${JSON.stringify(name)}: ${version},`)
    .join("\n");
const rustPairs = (entries) =>
  entries
    .map(([name, version]) => `    (${JSON.stringify(name)}, ${version}),`)
    .join("\n");
const kotlinPairs = (entries) =>
  entries
    .map(([name, version]) => `        ${JSON.stringify(name)} to ${version},`)
    .join("\n");
const goPairs = (entries) =>
  entries
    .map(([name, version]) => `\t${JSON.stringify(name)}: ${version},`)
    .join("\n");

const outputs = new Map([
  [
    "packages/player-runtime/src/compat/projection/presentation-capabilities.gen.ts",
    `// Code generated by scripts/generate-player-contracts.mjs; DO NOT EDIT.\n// Source: packages/manifest-schema/presentation-capabilities.json\n\n/** Declarative presentation capabilities implemented by the shared Player Runtime. */\n// prettier-ignore\nexport const SHARED_RUNTIME_DECLARATIVE_PRESENTATION_CAPABILITIES = Object.freeze({\n${tsMap(all)}\n}) satisfies Readonly<Record<string, number>>;\n\n/** Compatibility floor implemented by every currently supported legacy Player. */\n// prettier-ignore\nexport const BASELINE_DECLARATIVE_PRESENTATION_CAPABILITIES = Object.freeze({\n${tsMap(baseline)}\n}) satisfies Readonly<Record<string, number>>;\n`,
  ],
  [
    "apps/edge/tilecastd/src/presentation_capabilities.rs",
    `// Code generated by scripts/generate-player-contracts.mjs; DO NOT EDIT.\n// Source: packages/manifest-schema/presentation-capabilities.json\n\n/// Declarative presentation capabilities implemented by the shared Player Runtime.\npub const SHARED_RUNTIME_DECLARATIVE_PRESENTATION_CAPABILITIES: &[(&str, u32)] = &[\n${rustPairs(all)}\n];\n\n/// Compatibility floor implemented by every currently supported legacy Player.\npub const BASELINE_DECLARATIVE_PRESENTATION_CAPABILITIES: &[(&str, u32)] = &[\n${rustPairs(baseline)}\n];\n`,
  ],
  [
    "apps/player-windows/src/presentation_capabilities.rs",
    `// Code generated by scripts/generate-player-contracts.mjs; DO NOT EDIT.\n// Source: packages/manifest-schema/presentation-capabilities.json\n\n/// Declarative presentation capabilities implemented by the shared Player Runtime.\npub const SHARED_RUNTIME_DECLARATIVE_PRESENTATION_CAPABILITIES: &[(&str, u32)] = &[\n${rustPairs(all)}\n];\n\n/// Compatibility floor implemented by every currently supported legacy Player.\npub const BASELINE_DECLARATIVE_PRESENTATION_CAPABILITIES: &[(&str, u32)] = &[\n${rustPairs(baseline)}\n];\n`,
  ],
  [
    "apps/player-android/native/src/presentation_capabilities.rs",
    `// Code generated by scripts/generate-player-contracts.mjs; DO NOT EDIT.\n// Source: packages/manifest-schema/presentation-capabilities.json\n\n/// Declarative presentation capabilities implemented by the shared Player Runtime.\npub const SHARED_RUNTIME_DECLARATIVE_PRESENTATION_CAPABILITIES: &[(&str, u32)] = &[\n${rustPairs(all)}\n];\n\n/// Compatibility floor implemented by every currently supported legacy Player.\npub const BASELINE_DECLARATIVE_PRESENTATION_CAPABILITIES: &[(&str, u32)] = &[\n${rustPairs(baseline)}\n];\n`,
  ],
  [
    "apps/player-android/app/src/main/java/org/tilecast/player/network/PresentationCapabilities.gen.kt",
    `package org.tilecast.player.network\n\n// Code generated by scripts/generate-player-contracts.mjs; DO NOT EDIT.\n// Source: packages/manifest-schema/presentation-capabilities.json\nobject PresentationCapabilities {\n    /** Declarative presentation capabilities implemented by the shared Player Runtime. */\n    val SHARED_RUNTIME_DECLARATIVE_PRESENTATION_CAPABILITIES: Map<String, Int> = linkedMapOf(\n${kotlinPairs(all)}\n    )\n\n    /** Compatibility floor implemented by every currently supported legacy Player. */\n    val BASELINE_DECLARATIVE_PRESENTATION_CAPABILITIES: Map<String, Int> = linkedMapOf(\n${kotlinPairs(baseline)}\n    )\n}\n`,
  ],
  [
    "apps/server/internal/presentationcaps/capabilities.gen.go",
    `// Code generated by scripts/generate-player-contracts.mjs; DO NOT EDIT.\n// Source: packages/manifest-schema/presentation-capabilities.json\n\npackage presentationcaps\n\nvar sharedRuntime = map[string]int{\n${goPairs(all)}\n}\n\nvar baseline = map[string]int{\n${goPairs(baseline)}\n}\n\n// Supports reports whether name belongs to the declarative presentation vocabulary.\nfunc Supports(name string) bool {\n\t_, ok := sharedRuntime[name]\n\treturn ok\n}\n\n// Version returns the maximum version implemented by the shared Player Runtime.\nfunc Version(name string) int { return sharedRuntime[name] }\n\n// SharedRuntime returns a copy of the shared-runtime capability profile.\nfunc SharedRuntime() map[string]int { return clone(sharedRuntime) }\n\n// Baseline returns a copy of the compatibility floor used for legacy Players.\nfunc Baseline() map[string]int { return clone(baseline) }\n\nfunc clone(source map[string]int) map[string]int {\n\tresult := make(map[string]int, len(source))\n\tfor name, version := range source {\n\t\tresult[name] = version\n\t}\n\treturn result\n}\n`,
  ],
]);

const goOutputPath =
  "apps/server/internal/presentationcaps/capabilities.gen.go";
outputs.set(
  goOutputPath,
  execFileSync("gofmt", [], {
    input: outputs.get(goOutputPath),
    encoding: "utf8",
  }),
);

// The Android host's own renderer profile: one definition feeds the Rust
// packaged profile used to prepare manifests and the Kotlin ready report the
// live renderer advertises, so the two cannot drift.
const androidProfilePath = "apps/player-android/renderer-profile.json";
const androidProfile = JSON.parse(
  readFileSync(resolve(root, androidProfilePath), "utf8"),
);
if (androidProfile.schemaVersion !== 1) {
  throw new Error("Android renderer profile must use schemaVersion 1");
}
const profileText = (list, label) => {
  if (
    !Array.isArray(list) ||
    list.length === 0 ||
    new Set(list).size !== list.length
  ) {
    throw new Error(`Android renderer profile: ${label} must be a unique list`);
  }
  return list;
};
const profileFeatures = profileText(androidProfile.features, "features").map(
  (feature) => {
    if (typeof feature !== "string" || !/^[a-z][a-z0-9_.-]*$/.test(feature)) {
      throw new Error(`Android renderer profile: invalid feature ${feature}`);
    }
    return feature;
  },
);
const profileSchemas = (list, label) =>
  profileText(list, label).map((version) => {
    if (!Number.isInteger(version) || version < 1) {
      throw new Error(`Android renderer profile: invalid schema in ${label}`);
    }
    return version;
  });
const baselineSchemas = profileSchemas(
  androidProfile.presentationSchemas?.baseline,
  "presentationSchemas.baseline",
);
const componentSchemas = profileSchemas(
  androidProfile.presentationSchemas?.componentRuntime,
  "presentationSchemas.componentRuntime",
);
const namedVersion = (entry, label) => {
  if (
    !entry ||
    typeof entry.name !== "string" ||
    !/^[a-z][a-z0-9_.-]*$/.test(entry.name) ||
    !Number.isInteger(entry.version) ||
    entry.version < 1
  ) {
    throw new Error(`Android renderer profile: invalid ${label}`);
  }
  return entry;
};
const webRemote = namedVersion(androidProfile.webRemote, "webRemote");
const externalRuntime = namedVersion(
  androidProfile.externalWidgetRuntime,
  "externalWidgetRuntime",
);
// The Plugin API v2 host and the Shared Runtime services come from the one
// service vocabulary, so the Kotlin ready report offers exactly what Player
// Core's `shared_runtime_plugin_capabilities` does for every other host.
const playerServices = JSON.parse(
  readFileSync(
    resolve(root, "packages/plugin-sdk/player-services.json"),
    "utf8",
  ),
);
const pluginHost = namedVersion(
  {
    name: playerServices.host?.capability,
    version: playerServices.host?.version,
  },
  "plugin host",
);
// A runtime service that needs host help (`hostCapability`) is reported only
// by a host that provides it; Android provides none yet.
const runtimeServices = playerServices.services
  .filter(
    (service) => service.execution === "runtime" && !service.hostCapability,
  )
  .map((service) => namedVersion(service, `service ${service.name}`));
const profileHeader = `// Code generated by scripts/generate-player-contracts.mjs; DO NOT EDIT.\n// Source: ${androidProfilePath}, packages/plugin-sdk/player-services.json\n`;
outputs.set(
  "apps/player-android/native/src/renderer_profile.rs",
  `${profileHeader}\n/// Renderer features (\`renderer.ready\` vocabulary) the Android host implements.\npub const RENDERER_FEATURES: &[&str] = &[\n${profileFeatures.map((feature) => `    ${JSON.stringify(feature)},`).join("\n")}\n];\n\n/// Presentation schemas every supported WebView applies.\npub const BASELINE_PRESENTATION_SCHEMAS: &[u32] = &[${baselineSchemas.join(", ")}];\n\n/// Presentation schemas added once the Widget component runtime proves itself.\npub const COMPONENT_PRESENTATION_SCHEMAS: &[u32] = &[${componentSchemas.join(", ")}];\n\n/// The declarative capability the remote web host provides.\npub const WEB_REMOTE_CAPABILITY: &str = ${JSON.stringify(webRemote.name)};\npub const WEB_REMOTE_VERSION: u32 = ${webRemote.version};\n\n/// The Widget frame execution ABI capability every downloaded Widget uses.\npub const EXTERNAL_WIDGET_RUNTIME_CAPABILITY: &str = ${JSON.stringify(externalRuntime.name)};\npub const EXTERNAL_WIDGET_RUNTIME_VERSION: u32 = ${externalRuntime.version};\n`,
);
outputs.set(
  "apps/player-android/app/src/main/java/org/tilecast/player/core/RendererProfile.gen.kt",
  `package org.tilecast.player.core\n\n${profileHeader}object RendererProfile {\n    /** Renderer features (\`renderer.ready\` vocabulary) the Android host implements. */\n    val FEATURES: List<String> = listOf(\n${profileFeatures.map((feature) => `        ${JSON.stringify(feature)},`).join("\n")}\n    )\n\n    /** Presentation schemas every supported WebView applies. */\n    val BASELINE_PRESENTATION_SCHEMAS: List<Int> = listOf(${baselineSchemas.join(", ")})\n\n    /** Presentation schemas added once the Widget component runtime proves itself. */\n    val COMPONENT_PRESENTATION_SCHEMAS: List<Int> = listOf(${componentSchemas.join(", ")})\n\n    /** The declarative capability the remote web host provides. */\n    const val WEB_REMOTE_CAPABILITY = ${JSON.stringify(webRemote.name)}\n    const val WEB_REMOTE_VERSION = ${webRemote.version}\n\n    /** The Widget frame execution ABI capability every downloaded Widget uses. */\n    const val EXTERNAL_WIDGET_RUNTIME_CAPABILITY = ${JSON.stringify(externalRuntime.name)}\n    const val EXTERNAL_WIDGET_RUNTIME_VERSION = ${externalRuntime.version}\n\n    /** The Plugin API v2 host the shared Runtime hosts, and the Player services it implements. */\n    const val PLUGIN_HOST_CAPABILITY = ${JSON.stringify(pluginHost.name)}\n    const val PLUGIN_HOST_VERSION = ${pluginHost.version}\n    val SHARED_RUNTIME_PLAYER_SERVICES: Map<String, Int> = linkedMapOf(\n${runtimeServices.map((service) => `        ${JSON.stringify(service.name)} to ${service.version},`).join("\n")}\n    )\n}\n`,
);

const check = process.argv.includes("--check");
let stale = false;
for (const [relative, expected] of outputs) {
  const path = resolve(root, relative);
  if (check) {
    let current = "";
    try {
      current = readFileSync(path, "utf8");
    } catch {}
    if (current !== expected) {
      console.error(`player-contracts: generated file is stale: ${relative}`);
      stale = true;
    }
  } else {
    writeFileSync(path, expected);
  }
}
if (stale) process.exit(1);
