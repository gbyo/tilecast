#!/usr/bin/env node
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const sourcePath = resolve(
  root,
  "packages/manifest-schema/presentation-capabilities.json",
);
const contract = JSON.parse(readFileSync(sourcePath, "utf8"));

if (contract.schemaVersion !== 1 || !Array.isArray(contract.capabilities)) {
  throw new Error("presentation capability contract must use schemaVersion 1");
}

const seen = new Set();
const capabilities = contract.capabilities
  .map((entry) => {
    if (!entry || typeof entry !== "object") {
      throw new Error("capability entry must be an object");
    }
    const { name, version, baseline } = entry;
    if (typeof name !== "string" || !/^[a-z][a-z0-9_.-]*$/.test(name)) {
      throw new Error(`invalid capability name: ${String(name)}`);
    }
    if (seen.has(name)) throw new Error(`duplicate capability: ${name}`);
    seen.add(name);
    if (!Number.isInteger(version) || version < 1) {
      throw new Error(`invalid version for ${name}`);
    }
    if (typeof baseline !== "boolean") {
      throw new Error(`baseline must be boolean for ${name}`);
    }
    return { name, version, baseline };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

const all = capabilities.map(({ name, version }) => [name, version]);
const baseline = capabilities
  .filter((entry) => entry.baseline)
  .map(({ name, version }) => [name, version]);
const tsMap = (entries) =>
  entries
    .map(([name, version]) => `  ${JSON.stringify(name)}: ${version},`)
    .join("\n");
const rustPairs = (entries) =>
  entries
    .map(([name, version]) => `    (${JSON.stringify(name)}, ${version}),`)
    .join("\n");
const kotlinPairs = (entries) =>
  entries
    .map(([name, version]) => `        ${JSON.stringify(name)} to ${version},`)
    .join("\n");
const goPairs = (entries) =>
  entries
    .map(([name, version]) => `\t${JSON.stringify(name)}: ${version},`)
    .join("\n");

const outputs = new Map([
  [
    "packages/player-runtime/src/compat/projection/presentation-capabilities.gen.ts",
    `// Code generated by scripts/generate-player-contracts.mjs; DO NOT EDIT.\n// Source: packages/manifest-schema/presentation-capabilities.json\n\n/** Declarative presentation capabilities implemented by the shared Player Runtime. */\n// prettier-ignore\nexport const SHARED_RUNTIME_DECLARATIVE_PRESENTATION_CAPABILITIES = Object.freeze({\n${tsMap(all)}\n}) satisfies Readonly<Record<string, number>>;\n\n/** Compatibility floor implemented by every currently supported legacy Player. */\n// prettier-ignore\nexport const BASELINE_DECLARATIVE_PRESENTATION_CAPABILITIES = Object.freeze({\n${tsMap(baseline)}\n}) satisfies Readonly<Record<string, number>>;\n`,
  ],
  [
    "apps/edge/tilecastd/src/presentation_capabilities.rs",
    `// Code generated by scripts/generate-player-contracts.mjs; DO NOT EDIT.\n// Source: packages/manifest-schema/presentation-capabilities.json\n\n/// Declarative presentation capabilities implemented by the shared Player Runtime.\npub const SHARED_RUNTIME_DECLARATIVE_PRESENTATION_CAPABILITIES: &[(&str, u32)] = &[\n${rustPairs(all)}\n];\n\n/// Compatibility floor implemented by every currently supported legacy Player.\npub const BASELINE_DECLARATIVE_PRESENTATION_CAPABILITIES: &[(&str, u32)] = &[\n${rustPairs(baseline)}\n];\n`,
  ],
  [
    "apps/player-windows/src/presentation_capabilities.rs",
    `// Code generated by scripts/generate-player-contracts.mjs; DO NOT EDIT.\n// Source: packages/manifest-schema/presentation-capabilities.json\n\n/// Declarative presentation capabilities implemented by the shared Player Runtime.\npub const SHARED_RUNTIME_DECLARATIVE_PRESENTATION_CAPABILITIES: &[(&str, u32)] = &[\n${rustPairs(all)}\n];\n\n/// Compatibility floor implemented by every currently supported legacy Player.\npub const BASELINE_DECLARATIVE_PRESENTATION_CAPABILITIES: &[(&str, u32)] = &[\n${rustPairs(baseline)}\n];\n`,
  ],
  [
    "apps/player-android/native/src/presentation_capabilities.rs",
    `// Code generated by scripts/generate-player-contracts.mjs; DO NOT EDIT.\n// Source: packages/manifest-schema/presentation-capabilities.json\n\n/// Declarative presentation capabilities implemented by the shared Player Runtime.\npub const SHARED_RUNTIME_DECLARATIVE_PRESENTATION_CAPABILITIES: &[(&str, u32)] = &[\n${rustPairs(all)}\n];\n\n/// Compatibility floor implemented by every currently supported legacy Player.\npub const BASELINE_DECLARATIVE_PRESENTATION_CAPABILITIES: &[(&str, u32)] = &[\n${rustPairs(baseline)}\n];\n`,
  ],
  [
    "apps/player-android/app/src/main/java/org/tilecast/player/network/PresentationCapabilities.gen.kt",
    `package org.tilecast.player.network\n\n// Code generated by scripts/generate-player-contracts.mjs; DO NOT EDIT.\n// Source: packages/manifest-schema/presentation-capabilities.json\nobject PresentationCapabilities {\n    /** Declarative presentation capabilities implemented by the shared Player Runtime. */\n    val SHARED_RUNTIME_DECLARATIVE_PRESENTATION_CAPABILITIES: Map<String, Int> = linkedMapOf(\n${kotlinPairs(all)}\n    )\n\n    /** Compatibility floor implemented by every currently supported legacy Player. */\n    val BASELINE_DECLARATIVE_PRESENTATION_CAPABILITIES: Map<String, Int> = linkedMapOf(\n${kotlinPairs(baseline)}\n    )\n}\n`,
  ],
  [
    "apps/server/internal/presentationcaps/capabilities.gen.go",
    `// Code generated by scripts/generate-player-contracts.mjs; DO NOT EDIT.\n// Source: packages/manifest-schema/presentation-capabilities.json\n\npackage presentationcaps\n\nvar sharedRuntime = map[string]int{\n${goPairs(all)}\n}\n\nvar baseline = map[string]int{\n${goPairs(baseline)}\n}\n\n// Supports reports whether name belongs to the declarative presentation vocabulary.\nfunc Supports(name string) bool {\n\t_, ok := sharedRuntime[name]\n\treturn ok\n}\n\n// Version returns the maximum version implemented by the shared Player Runtime.\nfunc Version(name string) int { return sharedRuntime[name] }\n\n// SharedRuntime returns a copy of the shared-runtime capability profile.\nfunc SharedRuntime() map[string]int { return clone(sharedRuntime) }\n\n// Baseline returns a copy of the compatibility floor used for legacy Players.\nfunc Baseline() map[string]int { return clone(baseline) }\n\nfunc clone(source map[string]int) map[string]int {\n\tresult := make(map[string]int, len(source))\n\tfor name, version := range source {\n\t\tresult[name] = version\n\t}\n\treturn result\n}\n`,
  ],
]);

const goOutputPath =
  "apps/server/internal/presentationcaps/capabilities.gen.go";
outputs.set(
  goOutputPath,
  execFileSync("gofmt", [], {
    input: outputs.get(goOutputPath),
    encoding: "utf8",
  }),
);

const check = process.argv.includes("--check");
let stale = false;
for (const [relative, expected] of outputs) {
  const path = resolve(root, relative);
  if (check) {
    let current = "";
    try {
      current = readFileSync(path, "utf8");
    } catch {}
    if (current !== expected) {
      console.error(`player-contracts: generated file is stale: ${relative}`);
      stale = true;
    }
  } else {
    writeFileSync(path, expected);
  }
}
if (stale) process.exit(1);
