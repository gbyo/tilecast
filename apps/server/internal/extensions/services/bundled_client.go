// Generated plugin SDK files, relative to the repository root. The Go file
// is the typed client; the JSON file lets the TypeScript manifest schema and
// pluginctl check a manifest's "services" against the same registry.
const (
	BundledClientPath  = "packages/plugin-sdk/go/plugin/services_registry_gen.go"
	BundledCatalogPath = "packages/plugin-sdk/server-services.json"
)

// BundledCatalogSource renders the bundled capabilities as JSON.
func BundledCatalogSource() ([]byte, error) {
	type operation struct {
		Name     string   `json:"name"`
		Title    string   `json:"title"`
		Mutating bool     `json:"mutating"`
		Contexts []string `json:"contexts"`
	}
	type capability struct {
		ID          string      `json:"id"`
		Version     int         `json:"version"`
		Name        string      `json:"name"`
		Description string      `json:"description"`
		Contexts    []string    `json:"contexts"`
		Operations  []operation `json:"operations"`
	}
	out := []capability{}
	for _, entry := range All() {
		if !entry.AllowsCaller(CallerBundled) {
			continue
		}
		item := capability{ID: entry.ID, Version: entry.Version, Name: entry.Name, Description: entry.Description, Contexts: entry.Contexts}
		for _, op := range entry.Operations {
			item.Operations = append(item.Operations, operation{Name: op.Name, Title: op.Title, Mutating: op.Mutating, Contexts: op.Contexts})
		}
		out = append(out, item)
	}
	data, err := json.MarshalIndent(map[string]any{
		"$comment":     "Generated by apps/server/internal/extensions/services/gen from the Server service registry. Do not edit.",
		"capabilities": out,
	}, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(data, '\n'), nil
}

// BundledClientSource renders the plugin SDK's typed Server service client
// from this registry: the capabilities a bundled plugin may declare, and one
// method for each of their operations. Run `go run ./internal/extensions/services/gen`
// from apps/server after changing the registry; a test fails while the
// committed file differs.
func BundledClientSource() ([]byte, error) {
	var out bytes.Buffer
	out.WriteString(`// Code generated by apps/server/internal/extensions/services/gen from the
// Server service registry. DO NOT EDIT.

package plugin

import "context"

// ServerServices are the registry capabilities a bundled Plugin Manifest
// API 3 plugin may declare in "services" and call through Services.
var ServerServices = []ServerService{
`)
	capabilities := []Capability{}
	for _, capability := range All() {
		if capability.AllowsCaller(CallerBundled) {
			capabilities = append(capabilities, capability)
		}
	}
	for _, capability := range capabilities {
		fmt.Fprintf(&out, "\t{ID: %q, Version: %d, Name: %q, Description: %q, Contexts: %#v, Operations: []ServerOperation{\n",
			capability.ID, capability.Version, capability.Name, capability.Description, capability.Contexts)
		for _, operation := range capability.Operations {
			fmt.Fprintf(&out, "\t\t{Name: %q, Title: %q, Description: %q, Mutating: %t, Contexts: %#v},\n",
				operation.Name, operation.Title, operation.Description, operation.Mutating, operation.Contexts)
		}
		out.WriteString("\t}},\n")
	}
	out.WriteString("}\n")
	for _, capability := range capabilities {
		for _, operation := range capability.Operations {
			name := methodName(capability, operation)
			fmt.Fprintf(&out, "\n// %s calls %s: %s\nfunc (s *Services) %s(ctx context.Context, input, output any) error {\n\treturn s.Call(ctx, %q, input, output)\n}\n",
				name, operation.Name, strings.TrimSuffix(operation.Description, "."), name, operation.Name)
		}
	}
	return format.Source(out.Bytes())
}

// methodName joins the capability, a version suffix after version 1, and
// the method: targets.resolve@2/options gives TargetsResolveV2Options.
func methodName(capability Capability, operation Operation) string {
	method := operation.Name[strings.Index(operation.Name, "/")+1:]
	name := pascal(capability.ID)
	if capability.Version > 1 {
		name += fmt.Sprintf("V%d", capability.Version)
	}
	return name + pascal(method)
}

func pascal(value string) string {
	var out strings.Builder
	upper := true
	for _, r := range value {
		if r == '.' || r == '-' || r == '_' {
			upper = true
			continue
		}
		if upper {
			out.WriteRune(unicode.ToUpper(r))
			upper = false
		} else {
			out.WriteRune(r)
		}
	}
	return out.String()
}
