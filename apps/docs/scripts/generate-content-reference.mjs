import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const definitionsDir = path.resolve(
  here,
  "../../server/internal/contentdefs/definitions",
);
const outputPath = path.resolve(
  here,
  "../src/content/docs/reference/content-definitions.md",
);
const checkOnly = process.argv.includes("--check");

const escapeCell = (value) =>
  String(value ?? "")
    .replaceAll("\\", "\\\\")
    .replaceAll("|", "\\|")
    .replaceAll("\n", " ")
    .trim();

const names = (await fs.readdir(definitionsDir))
  .filter((name) => name.endsWith(".json"))
  .sort();

const widgets = [];
const dataSources = [];

for (const name of names) {
  const document = JSON.parse(
    await fs.readFile(path.join(definitionsDir, name), "utf8"),
  );
  for (const definition of document.widgets ?? []) {
    widgets.push({ ...definition, source: name });
  }
  for (const definition of document.dataSources ?? []) {
    dataSources.push({ ...definition, source: name });
  }
}

function markdownTable(headers, records) {
  const rows = records.map((record) => record.map(escapeCell));
  const widths = headers.map((header, index) =>
    Math.max(3, header.length, ...rows.map((row) => row[index]?.length ?? 0)),
  );
  const line = (row) =>
    `| ${row.map((cell, index) => cell.padEnd(widths[index])).join(" | ")} |`;
  return [
    line(headers),
    `| ${widths.map((width) => "-".repeat(width)).join(" | ")} |`,
    ...rows.map(line),
  ].join("\n");
}

const widgetTable = markdownTable(
  ["Name", "ID", "Kind", "Category", "Runtime", "Source"],
  widgets.map((definition) => [
    definition.name,
    "`" + definition.id + "`",
    definition.kind || "widget",
    definition.category,
    definition.runtime,
    "`" + definition.source + "`",
  ]),
);

const dataSourceTable = markdownTable(
  ["Name", "ID", "Category", "Output", "Adapter", "Source"],
  dataSources.map((definition) => [
    definition.name,
    "`" + definition.id + "`",
    definition.category,
    definition.outputSchema?.kind || "",
    definition.adapterId || "legacy",
    "`" + definition.source + "`",
  ]),
);

const content = `---
title: Content definition reference
description: Generated list of the Widget, App, and Data Source definitions included with this Tilecast version.
---

<!-- Generated by apps/docs/scripts/generate-content-reference.mjs. Do not edit by hand. -->

This page is generated from \`apps/server/internal/contentdefs/definitions/*.json\`. It is a source reference, not a setup guide or a promise that every Player supports every item.

Use the regular Widget and Data Source guides when you need setup instructions.

## Widget and App definitions

${widgetTable}

## Data Source definitions

${dataSourceTable}

## Keep this page current

Run:

\`\`\`sh
npm run generate:content-reference --workspace @tilecast/docs
\`\`\`

The docs check and build run the generator in \`--check\` mode and fail if this committed page is out of date.
`;

if (checkOnly) {
  let existing = "";
  try {
    existing = await fs.readFile(outputPath, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  if (existing !== content) {
    console.error(
      "Content definition reference is stale. Run the docs generator and commit the result.",
    );
    process.exit(1);
  }
  process.exit(0);
}

await fs.mkdir(path.dirname(outputPath), { recursive: true });
await fs.writeFile(outputPath, content);
console.log(path.relative(process.cwd(), outputPath));
