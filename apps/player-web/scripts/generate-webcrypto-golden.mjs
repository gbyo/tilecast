// Regenerates the golden Browser device signature the Go server verifies:
//   node apps/player-web/scripts/generate-webcrypto-golden.mjs
// The key is a non-extractable P-256 WebCrypto key exactly as the Browser
// Host creates it, and the signature covers the server's challenge message.
import { webcrypto } from "node:crypto";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const target = fileURLToPath(
  new URL(
    "../../server/internal/devices/testdata/browser_webcrypto_golden.json",
    import.meta.url,
  ),
);
const { subtle } = webcrypto;
const pair = await subtle.generateKey(
  { name: "ECDSA", namedCurve: "P-256" },
  true,
  ["sign", "verify"],
);
const publicKey = await subtle.exportKey("jwk", pair.publicKey);
const slotId = "5d2c9a1e-40a7-4c52-8e3b-1f6d7a9b0c11";
const bindingId = "a8f1d3b2-6c4e-4b9a-9d57-2e0c1b7f3a44";
// 32 random bytes, base64url: the 43-character shape the server issues.
const nonce = Buffer.from("0123456789abcdef0123456789abcdef").toString(
  "base64url",
);
const message = `tilecast-browser-player-v1:${slotId}:${bindingId}:${nonce}`;
const sign = async (text) =>
  Buffer.from(
    await subtle.sign(
      { name: "ECDSA", hash: "SHA-256" },
      pair.privateKey,
      new TextEncoder().encode(text),
    ),
  ).toString("base64url");
const golden = {
  note: "Generated by apps/player-web/scripts/generate-webcrypto-golden.mjs. Do not edit.",
  publicKey: {
    kty: publicKey.kty,
    crv: publicKey.crv,
    x: publicKey.x,
    y: publicKey.y,
    ext: true,
    key_ops: ["verify"],
  },
  slotId,
  bindingId,
  nonce,
  message,
  signature: await sign(message),
  // What the previous Browser Host signed. The server must reject it.
  nonceOnlySignature: await sign(nonce),
};
// Short arrays stay on one line, which is also how Prettier formats them.
const text = JSON.stringify(golden, null, 2).replace(
  /\[\n\s+("verify")\n\s+\]/,
  '["verify"]',
);
writeFileSync(target, text + "\n");
console.log(`wrote ${target}`);
