/**
 * Regenerate the portable package-manifest JSON Schema from the Zod source.
 * Run with `npm run generate`; `make generate` keeps the checked-in copy
 * current and `make generated-check` fails on drift.
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import prettier from "prettier";
import { packageManifestJSONSchema } from "../src/manifest.ts";
import { externalPluginManifestJSONSchema } from "../src/external-plugin.ts";
import {
  buildExternalPluginFrame,
  EXTERNAL_PLUGIN_BUNDLE_PLACEHOLDER,
  EXTERNAL_PLUGIN_FRAME_POLICY,
} from "../src/player-frame.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const path = join(root, "schema", "tilecast-package.schema.json");
const options = (await prettier.resolveConfig(path)) ?? {};
const text = await prettier.format(
  JSON.stringify(packageManifestJSONSchema()),
  { ...options, filepath: path },
);
writeFileSync(path, text);
console.log(`wrote ${path}`);
const externalPath = join(root, "schema", "external-plugin.schema.json");
writeFileSync(
  externalPath,
  await prettier.format(JSON.stringify(externalPluginManifestJSONSchema()), {
    ...options,
    filepath: externalPath,
  }),
);
console.log(`wrote ${externalPath}`);
const framePath = join(
  root,
  "..",
  "..",
  "apps",
  "server",
  "internal",
  "extensions",
  "sandbox",
  "plugin_frame.gen.go",
);
writeFileSync(
  framePath,
  `// Code generated by package-sdk. DO NOT EDIT.
// Run npm run packages:generate.

package sandbox

const PluginBundlePlaceholder = ${JSON.stringify(EXTERNAL_PLUGIN_BUNDLE_PLACEHOLDER)}
const PluginFramePolicy = ${JSON.stringify(EXTERNAL_PLUGIN_FRAME_POLICY)}
const PluginTemplate = ${JSON.stringify(buildExternalPluginFrame(EXTERNAL_PLUGIN_BUNDLE_PLACEHOLDER))}
`,
);
console.log(`wrote ${framePath}`);
