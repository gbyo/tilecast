/**
 * The generated native contribution registry. A first-party native
 * contribution is a Rust crate at plugins/<plugin>/native/<id>/ that exports
 * `pub fn contribution() -> Box<dyn NativePluginContribution>`. Rust has no
 * compile-time glob, so this file derives the one crate that links them:
 * `packages/plugin-native-registry`. A Player build opts in by depending on
 * that crate and passing `contributions()` to `NativePluginHost::new`.
 *
 * Nothing here knows a plugin, a platform, or a service. A contribution that
 * a Player cannot support (a required native service is missing) stays
 * unsupported at run time; the registry never decides support.
 */
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import type { DiscoveredPlugin, Repo } from "./repo.ts";

export const NATIVE_REGISTRY_DIR = "packages/plugin-native-registry";
export const NATIVE_REGISTRY_CARGO = `${NATIVE_REGISTRY_DIR}/Cargo.toml`;
export const NATIVE_REGISTRY_LIB = `${NATIVE_REGISTRY_DIR}/src/lib.rs`;
export const NATIVE_REGISTRY_PACKAGE = "plugin-native-registry";

/** The signature every native contribution crate exports. */
export const CONTRIBUTION_ENTRY =
  /pub\s+fn\s+contribution\s*\(\s*\)\s*->\s*Box<dyn\s+(?:player_core::)?NativePluginContribution\s*>/;

export interface NativeCrate {
  plugin: string;
  contribution: string;
  /** Cargo package name. */
  name: string;
  /** Path from the registry crate to the contribution crate. */
  path: string;
}

/** The `[package] name` of a Cargo manifest, or null. */
export function cargoPackageName(text: string): string | null {
  let inPackage = false;
  for (const raw of text.split("\n")) {
    const line = raw.trim();
    if (line.startsWith("[")) {
      inPackage = line === "[package]";
      continue;
    }
    const match = /^name\s*=\s*"([^"]+)"/.exec(line);
    if (inPackage && match?.[1]) return match[1];
  }
  return null;
}

/** Every declared native crate that exists, in plugin and contribution order. */
export function nativeCrates(repo: Repo): NativeCrate[] {
  const crates: NativeCrate[] = [];
  for (const plugin of [...repo.plugins].sort((a, b) =>
    a.manifest.id < b.manifest.id ? -1 : 1,
  )) {
    crates.push(...pluginCrates(plugin));
  }
  return crates;
}

function pluginCrates(plugin: DiscoveredPlugin): NativeCrate[] {
  if (plugin.manifest.apiVersion !== 2) return [];
  const ids = (plugin.manifest.player?.native ?? [])
    .map((native) => native.id)
    .sort();
  const crates: NativeCrate[] = [];
  for (const id of ids) {
    const cargo = join(plugin.path, "native", id, "Cargo.toml");
    if (!existsSync(cargo)) continue;
    const name = cargoPackageName(readFileSync(cargo, "utf8"));
    if (!name) continue;
    crates.push({
      plugin: plugin.manifest.id,
      contribution: id,
      name,
      path: `../../plugins/${plugin.dir}/native/${id}`,
    });
  }
  return crates;
}

const HEADER =
  "Code generated by pluginctl from plugins/*/tilecast.plugin.json. DO NOT EDIT.";

export function nativeRegistryCargo(crates: readonly NativeCrate[]): string {
  return [
    `# ${HEADER}`,
    "[package]",
    `name = "${NATIVE_REGISTRY_PACKAGE}"`,
    'description = "The first-party native plugin contributions compiled into a Player build."',
    'version = "0.1.0"',
    "edition.workspace = true",
    "license.workspace = true",
    "publish.workspace = true",
    "rust-version.workspace = true",
    "",
    "[dependencies]",
    "player-core.workspace = true",
    ...crates.map((crate) => `${crate.name} = { path = "${crate.path}" }`),
    "",
    "[lints]",
    "workspace = true",
    "",
  ].join("\n");
}

export function nativeRegistryLib(crates: readonly NativeCrate[]): string {
  const ident = (name: string) => name.replaceAll("-", "_");
  const body =
    crates.length === 0
      ? ["    Vec::new()"]
      : [
          "    let mut all: Vec<Box<dyn NativePluginContribution>> = Vec::new();",
          ...crates.map(
            (crate) => `    all.push(${ident(crate.name)}::contribution());`,
          ),
          "    all",
        ];
  return [
    `// ${HEADER}`,
    "//! The first-party native plugin contributions this release compiles in.",
    "//!",
    "//! A Player build passes `contributions()` to `NativePluginHost::new` with",
    "//! the native services it provides. A contribution that needs a service the",
    "//! build does not provide stays unsupported; this list never decides support.",
    "use player_core::NativePluginContribution;",
    "",
    "/// One fresh instance of every compiled-in native contribution, in plugin",
    "/// and contribution order.",
    "pub fn contributions() -> Vec<Box<dyn NativePluginContribution>> {",
    ...body,
    "}",
    "",
  ].join("\n");
}
